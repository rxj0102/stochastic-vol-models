"""Value-at-Risk for option positions that accounts for stochastic volatility.

The P&L distribution is generated by simulating Heston spot/variance paths to a
short horizon and repricing the position on each scenario, so that vol-of-vol
and the leverage effect feed directly into the tail.
"""

from __future__ import annotations

from dataclasses import replace
from typing import Dict

import numpy as np

from fourier_pricing.cos_method import COSMethodPricer
from simulation.heston_qe import HestonQESimulator

__all__ = ["VolVaR"]


class VolVaR:
    """Simulation-based VaR/ES for a single Heston-priced option."""

    def __init__(self) -> None:
        self.pricer = COSMethodPricer()
        self.sim = HestonQESimulator()

    def pnl_distribution(
        self, S0, K, T, r, q, params, horizon=1.0 / 252, n_scenarios=20000, seed=None
    ) -> np.ndarray:
        """Return the simulated option P&L over ``horizon`` (one step)."""
        S, V = self.sim.simulate(
            S0, params.V0, horizon, r, q, params, n_scenarios, 1, seed
        )
        ST, VT = S[:, -1], V[:, -1]
        base = self.pricer.price(S0, K, T, r, q, params, "call")
        T_rem = max(T - horizon, 1e-6)
        pnl = np.empty(n_scenarios)
        for i in range(n_scenarios):
            p_i = replace(params, V0=max(VT[i], 1e-8))
            pnl[i] = self.pricer.price(ST[i], K, T_rem, r, q, p_i, "call") - base
        return pnl

    def var_es(
        self,
        S0,
        K,
        T,
        r,
        q,
        params,
        alpha=0.99,
        horizon=1.0 / 252,
        n_scenarios=5000,
        seed=None,
    ) -> Dict[str, float]:
        """Return VaR and Expected Shortfall at confidence ``alpha``."""
        pnl = self.pnl_distribution(S0, K, T, r, q, params, horizon, n_scenarios, seed)
        var = -np.quantile(pnl, 1.0 - alpha)
        es = -pnl[pnl <= -var].mean() if np.any(pnl <= -var) else var
        return {
            "VaR": float(var),
            "ES": float(es),
            "alpha": alpha,
            "mean_pnl": float(pnl.mean()),
            "std_pnl": float(pnl.std()),
        }
